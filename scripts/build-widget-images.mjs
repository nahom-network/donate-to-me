/**
 * Regenerate `src/widget-images.ts` from `images/`.
 *
 *   node scripts/build-widget-images.mjs [logoSize] [badgeSize]
 *
 * A widget must stay under 4096 bytes after zlib level 9, and a data: image
 * barely compresses, so every byte here is bought from the widget's own CSS:
 *
 * - PNG-8 with a small palette beats WebP ~3x on these flat marks.
 * - The asset is sized to its on-screen pixel size, so the client never scales.
 * - The badge illustration is greyscaled and quantised to 4 colours; at 34 px
 *   that reads as a crisp stencil instead of grey mush, and costs ~340 B.
 *
 * `sharp` comes in through wrangler, so this is a one-off maintenance script,
 * not part of `pnpm run deploy`: the generated file is committed.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const sharp = require("sharp");

const LOGO_SIZE = Number(process.argv[2] ?? 28);
const BADGE_SIZE = Number(process.argv[3] ?? 34);
const OUT = path.join(process.cwd(), "src", "widget-images.ts");

// Fewer palette entries = fewer bytes. Telebirr and M-Pesa are flat enough for
// 4 colours at this size; CBE Birr keeps its yellow accent at 8.
const sources = [
  ["LOGO_TELEBIRR", "images/telebirr-logo.png", LOGO_SIZE, 4, false],
  ["LOGO_MPESA", "images/M-PESA-logo.png", LOGO_SIZE, 4, false],
  ["LOGO_CBE", "images/cbe-birr-logo.png", LOGO_SIZE, 8, false],
  ["BRAND_IMAGE", "images/sticker-logo.webp", BADGE_SIZE, 4, true],
];

const lines = [
  "/** Generated by `node scripts/build-widget-images.mjs`. Do not edit by hand. */",
  "",
];

let bytes = 0;
for (const [name, file, size, colours, greyscale] of sources) {
  let pipeline = sharp(fs.readFileSync(file))
    .trim()
    .resize(size, size, {
      fit: "contain",
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    });
  if (greyscale) pipeline = pipeline.greyscale();
  const buffer = await pipeline
    .png({ palette: true, colours, effort: 10, compressionLevel: 9 })
    .toBuffer();
  bytes += buffer.length;
  lines.push(
    `export const ${name} =`,
    `  "data:image/png;base64,${buffer.toString("base64")}";`,
    "",
  );
  console.log(`${name.padEnd(14)} ${size}px ${colours}c  ${buffer.length} B`);
}

fs.writeFileSync(OUT, lines.join("\n"));
const base64 = lines.join("").match(/base64,[^"]+/g)?.reduce((n, s) => n + s.length, 0) ?? 0;
console.log(`total ${bytes} B binary, ${base64} B base64 -> ${OUT}`);
